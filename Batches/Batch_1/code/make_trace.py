#!/usr/bin/env python3
"""make_trace.py -- writes ../extras/TRACE.md and ../results/search_tree.png from the REAL solver run."""
import os
from main_solution import solve

A = [15000, 22000, 35000, 40000, 48000, 53000, 61000]
HERE = os.path.dirname(os.path.abspath(__file__))
events = []                      # (kind, sid, depth, vals, cur, info)
nodes = {}                       # sid -> dict(parent, depth, vals, cur, sol, cuts)
stack = {}                       # depth -> sid

def tr(kind, sid, depth, vals, cur, info):
    events.append((kind, sid, depth, list(vals), cur, info))
    if kind == "visit":
        stack[depth] = sid
        nodes[sid] = dict(parent=stack.get(depth - 1), depth=depth, vals=list(vals), cur=cur, sol=False, cuts=[])
    elif kind == "solution":
        nodes[sid]["sol"] = True
    else:
        nodes[sid]["cuts"].append((kind, info))

res = solve(A, 110000, 0, trace=tr)
k = lambda v: f"{v // 1000}"

lines = ["# Complete execution trace (generated by `code/make_trace.py` from the real solver)", "",
         "Instance (Rs thousands): A = {15, 22, 35, 40, 48, 53, 61}, target = 110, tolerance = 0.",
         "Items are sorted ascending (already sorted here). `suffix[j]` = sum of items j..7.",
         "A *state* S_k is one recursive call = one candidate subset. `OVERSHOOT` = next item would push the sum above 110;",
         "`UNREACHABLE` = even taking every remaining item from the candidate onward stays below 110.", "",
         "| State | Subset (thousands) | Sum | Event(s) at this state |", "|---|---|---|---|"]
for sid in sorted(nodes):
    nd = nodes[sid]
    ev = []
    if nd["sol"]:
        ev.append("**SOLUTION**")
    for kind, (j, v, val, skipped) in nd["cuts"]:
        if kind == "prune_overshoot":
            ev.append(f"prune OVERSHOOT: +{k(v)} -> {k(val)} > 110, skips {skipped} branch(es)")
        else:
            ev.append(f"prune UNREACHABLE: max reachable {k(val)} < 110, skips {skipped} branch(es)")
    sub = "{" + ", ".join(k(x) for x in nd["vals"]) + "}" if nd["vals"] else "{} (empty, root)"
    lines.append(f"| S{sid} | {sub} | {k(nd['cur'])} | {'<br>'.join(ev) if ev else 'children expanded'} |")
lines += ["", f"**Totals:** states = {res.states}, solutions = {len(res.solutions)}, overshoot cut-offs = {res.prune_overshoot}, "
          f"unreachable cut-offs = {res.prune_unreachable}, child branches skipped = {res.skipped_children}, all subsets = 128.", "",
          "**Solutions:** " + "; ".join("{" + ", ".join(k(A[i]) for i in s) + "}" for s in res.solutions)]
with open(os.path.join(HERE, "..", "extras", "TRACE.md"), "w") as f:
    f.write("\n".join(lines) + "\n")

# ---------- tree figure ----------
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
children = {}
for sid, nd in nodes.items():
    children.setdefault(nd["parent"], []).append(sid)
xpos, counter = {}, [0]
def layout(s):
    ch = children.get(s, [])
    if not ch:
        xpos[s] = counter[0]; counter[0] += 1
    else:
        for c in ch: layout(c)
        xpos[s] = sum(xpos[c] for c in ch) / len(ch)
layout(1)
fig, ax = plt.subplots(figsize=(15, 5.2))
for sid, nd in nodes.items():
    if nd["parent"]:
        ax.plot([xpos[nd["parent"]], xpos[sid]], [-nd["depth"] + 1, -nd["depth"]], color="#999", lw=1, zorder=1)
for sid, nd in nodes.items():
    x, y = xpos[sid], -nd["depth"]
    col = "#7fd48a" if nd["sol"] else "#dfe9f7"
    ax.scatter([x], [y], s=520, color=col, edgecolor="#335", zorder=2)
    lab = "root" if not nd["vals"] else k(nd["vals"][-1])
    ax.text(x, y + 0.03, lab, ha="center", va="center", fontsize=8, zorder=3)
    ax.text(x, y - 0.22, f"={k(nd['cur'])}", ha="center", va="center", fontsize=7, color="#333")
    cuts = nd["cuts"]
    if cuts:
        kinds = {c[0] for c in cuts}
        mark = "x" if "prune_unreachable" in kinds and "prune_overshoot" not in kinds else ("x" if True else "")
        tag = "U" if "prune_unreachable" in kinds else "O"
        if len(kinds) == 2: tag = "O+U"
        ax.text(x, y - 0.42, f"cut:{tag}", ha="center", va="center", fontsize=6, color="#b00020")
ax.set_axis_off()
ax.set_title("Search tree on A = {15,22,35,40,48,53,61}, target 110: 35 states (of 128 subsets). Node label = last item added, '=' running sum; "
             "green = solution; cut:O overshoot, cut:U unreachable", fontsize=8)
fig.tight_layout()
fig.savefig(os.path.join(HERE, "..", "results", "search_tree.png"), dpi=140)
print("states", res.states, "solutions", len(res.solutions))
